import {test,expect} from '@playwright/test';
test('complete command-center workflow',async({page,request})=>{
 await request.post('/api/scenario',{data:{count:50,range:250,seed:42}});
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('/');
 await expect(page.getByText('Live connection',{exact:true})).toBeVisible();
 await expect(page.getByText('9.82',{exact:false}).first()).toBeVisible();
 await page.getByRole('button',{name:'Trigger event',exact:true}).click();
 await expect(page.locator('.latest-event')).toBeVisible();
 await request.post('/api/nodes/0/toggle');
 await expect(page.locator('.metric').nth(2).locator('.metric-value')).toContainText('0');
 await page.getByRole('button',{name:'Trigger event',exact:true}).click();
 await expect(page.getByText('No gateway route',{exact:false}).first()).toBeVisible();
 await request.post('/api/nodes/0/toggle');
 await page.getByRole('button',{name:'Network intelligence',exact:true}).click();
 await page.getByRole('button',{name:/Inspect sensor/}).first().click();
 await expect(page.getByText('Current route:',{exact:false})).toBeVisible();
 await page.getByRole('button',{name:'Disable sensor',exact:true}).click();
 await expect(page.getByRole('button',{name:'Restore sensor',exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Restore sensor',exact:true}).click();
 await page.getByRole('button',{name:'Close sensor'}).click();
 await page.getByRole('button',{name:'Optimize deployment'}).click();
 await expect(page.getByText('Deployment comparison',{exact:true})).toBeVisible();
 await expect(page.locator('.compare-grid').first()).toContainText('Estimated coverage');
 await page.getByRole('button',{name:'Event log',exact:false}).click();
 await expect(page.locator('tbody tr')).toHaveCount(2);
 await page.getByRole('button',{name:'Overview',exact:true}).click();
 await page.getByLabel('Transmission range').fill('200');
 await page.getByRole('button',{name:'Apply scenario'}).click();
 await expect(page.getByText('Position-based network · 200 m nominal transmission range')).toBeVisible();
 await page.screenshot({path:'/tmp/forestmesh-desktop.png',fullPage:true});
 await page.setViewportSize({width:390,height:844});
 await expect(page.locator('.map-area')).toBeVisible();
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBeTruthy();
 await page.screenshot({path:'/tmp/forestmesh-mobile.png',fullPage:true});
 expect(errors).toEqual([]);
});
